#ifndef LAYOUT_H
#define LAYOUT_H

// 1024*1024*1024*512 = 0x4000000000 (half of sv39 space for risc-v)
// 0x4000000000 would be jump but top half is top half

#define KERNEL_VMA_START 0xffffffc000000000

// Kernel mapping

// 0xFFFFFFFFFFFFF000 - 0xFFFFFFFFFFFFFFFF blank guard

// 0xFFFFFFFFFFFFE000 - 0xFFFFFFFFFFFEFFF trap frame
#define TRAPFRAME_ADDRESS 0xFFFFFFFFFFFFE000

// 0xFFFFFFFFFFFFD000 - 0xFFFFFFFFFFFFDFFF blank guard

// 0xFFFFFFFFFFFF9000 - 0xFFFFFFFFFFFCFFF process kernel stack
#define PROC_KERN_STACK_START 0xFFFFFFFFFFFFA000
#define PROC_KERN_STACK_SIZE (4096 * 4)
#define PROC_KERN_STACK_TOP (PROC_KERN_STACK_START + PROC_KERN_STACK_SIZE - 1)

// 0xFFFFFFFFFFFF8000 - 0xFFFFFFFFFFFF8FFF blank guard

// 0xFFFFFFFFFFFF4000 - 0xFFFFFFFFFFFF7FFF hart kernel stack
#define HART_KERN_STACK_START 0xFFFFFFFFFFFF4000
#define HART_KERN_STACK_SIZE (4096 * 4) // reused for actual size creating
#define HART_KERN_STACK_TOP (HART_KERN_STACK_START + HART_KERN_STACK_SIZE - 1)

// bottom of mapping
#define KERN_MAPPING_BOTTOM 0xFFFFFFFFFFFF3000

#endif